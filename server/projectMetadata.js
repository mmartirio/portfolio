// Lê os metadados públicos (title, description, og:*, theme-color) dos sites
// publicados e monta a lista de projetos do portfólio.
// Usado pela função /api/projects (Vercel) e pelo servidor de dev do Vite.

const FETCH_TIMEOUT_MS = 6000;
const USER_AGENT = 'Mozilla/5.0 (compatible; PortfolioMetadataBot/1.0)';

const GENERIC_TITLES = /^(document|react app|vite \+ react|vite app|create next app|login|home|index|untitled|app)$/i;
const GENERIC_DESCRIPTIONS = [/created using create-react-app/i, /generated by create next app/i, /^web site created/i];
const LOCAL_HOSTS = /^(localhost|127\.0\.0\.1|0\.0\.0\.0)$/i;

const FRAMEWORK_LABELS = {
  nextjs: 'Next.js · React',
  vite: 'React · Vite',
  'create-react-app': 'React · JavaScript',
  flask: 'Python · Flask',
  fastapi: 'Python · FastAPI',
  astro: 'Astro',
  nuxtjs: 'Nuxt · Vue',
  vue: 'Vue',
  svelte: 'Svelte',
  sveltekit: 'SvelteKit',
  angular: 'Angular',
  remix: 'Remix · React',
  express: 'Node.js · Express',
};

export function decodeEntities(text = '') {
  return text
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseAttributes(tag) {
  const attrs = {};
  const re = /([a-zA-Z:-]+)\s*=\s*("([^"]*)"|'([^']*)'|([^\s>]+))/g;
  let match;
  while ((match = re.exec(tag))) {
    attrs[match[1].toLowerCase()] = match[3] ?? match[4] ?? match[5] ?? '';
  }
  return attrs;
}

// Resolve URLs relativas e corrige imagens publicadas apontando para
// localhost (erro comum de build) usando a origem do próprio site.
export function resolveUrl(value, pageUrl) {
  if (!value) return null;
  try {
    const page = new URL(pageUrl);
    const url = new URL(value, page);
    if (LOCAL_HOSTS.test(url.hostname)) {
      return new URL(url.pathname + url.search, page.origin).href;
    }
    if (url.protocol === 'http:' && url.hostname === page.hostname) url.protocol = 'https:';
    return url.href;
  } catch {
    return null;
  }
}

export function parseMetadata(html, pageUrl) {
  const head = html.slice(0, 200_000);
  const meta = {};
  for (const tag of head.match(/<meta\b[^>]*>/gi) ?? []) {
    const attrs = parseAttributes(tag);
    const key = (attrs.property || attrs.name || '').toLowerCase();
    if (key && attrs.content !== undefined && meta[key] === undefined) {
      meta[key] = decodeEntities(attrs.content);
    }
  }

  let icon = null;
  for (const tag of head.match(/<link\b[^>]*>/gi) ?? []) {
    const attrs = parseAttributes(tag);
    const rel = (attrs.rel || '').toLowerCase();
    if (attrs.href && (rel === 'apple-touch-icon' || (!icon && rel.split(/\s+/).includes('icon')))) {
      icon = attrs.href;
    }
  }

  const titleTag = head.match(/<title[^>]*>([^<]*)<\/title>/i);

  return {
    title: meta['og:title'] || decodeEntities(titleTag?.[1] ?? '') || null,
    siteName: meta['og:site_name'] || meta['application-name'] || null,
    description: meta['og:description'] || meta.description || null,
    image: resolveUrl(meta['og:image'] || meta['twitter:image'], pageUrl),
    themeColor: /^#[0-9a-f]{3,8}$/i.test(meta['theme-color'] ?? '') ? meta['theme-color'] : null,
    icon: resolveUrl(icon, pageUrl),
  };
}

// "Davi Foto Vídeo | Fotografia e vídeo..." -> "Davi Foto Vídeo"
export function cleanName(title, siteName) {
  const candidate = siteName || title;
  if (!candidate) return null;
  const name = candidate.split(/\s+[|–—·]\s+|\s+-\s+/)[0].trim();
  return name && !GENERIC_TITLES.test(name) ? name : null;
}

// Remove o prefixo repetido "Nome - " das descrições.
export function cleanDescription(description, name) {
  if (!description || GENERIC_DESCRIPTIONS.some((re) => re.test(description))) return null;
  if (name) {
    const prefix = new RegExp(`^${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*[-–—:|]\\s*`, 'i');
    const stripped = description.replace(prefix, '');
    if (stripped !== description && stripped.length > 0) {
      return stripped.charAt(0).toUpperCase() + stripped.slice(1);
    }
  }
  return description;
}

export async function fetchMetadata(url, fetchImpl = fetch) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    const res = await fetchImpl(url, {
      headers: { 'user-agent': USER_AGENT, accept: 'text/html' },
      redirect: 'follow',
      signal: controller.signal,
    });
    if (!res.ok) return null;
    const html = await res.text();
    return parseMetadata(html, res.url || url);
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

function productionUrl(project) {
  const aliases = project.targets?.production?.alias ?? project.alias?.map((a) => a.domain) ?? [];
  const domain = aliases.find((a) => a && !a.includes('*'));
  return domain ? `https://${domain}` : null;
}

// Descoberta automática: lista os projetos da conta Vercel (requer token).
export async function discoverVercelProjects({ token, teamId, fetchImpl = fetch }) {
  if (!token) return [];
  const params = new URLSearchParams({ limit: '100' });
  if (teamId) params.set('teamId', teamId);
  try {
    const res = await fetchImpl(`https://api.vercel.com/v10/projects?${params}`, {
      headers: { authorization: `Bearer ${token}` },
    });
    if (!res.ok) return [];
    const data = await res.json();
    return (data.projects ?? [])
      .map((p) => ({
        vercelProject: p.name,
        url: productionUrl(p),
        technologies: FRAMEWORK_LABELS[p.framework] ?? null,
        updatedAt: p.updatedAt ?? 0,
      }))
      .filter((p) => p.url);
  } catch {
    return [];
  }
}

function prettifySlug(slug) {
  return slug
    .replace(/[-_]+/g, ' ')
    .replace(/\b(frontend|front|web|app)\b/gi, '')
    .trim()
    .replace(/^\w/, (c) => c.toUpperCase());
}

export function mergeProject(config, live) {
  const name = config.override?.name ?? cleanName(live?.title, live?.siteName) ?? config.fallback?.name;
  const description =
    config.override?.description ?? cleanDescription(live?.description, name) ?? config.fallback?.description ?? '';
  return {
    id: config.id,
    url: config.url,
    name,
    description,
    category: config.category ?? 'Projeto',
    technologies: config.technologies ?? '',
    image: config.override?.image ?? live?.image ?? null,
    icon: live?.icon ?? null,
    themeColor: config.themeColor ?? live?.themeColor ?? null,
    live: Boolean(live),
  };
}

export async function getProjects({ projects, excluded = [], env = {}, fetchImpl = fetch }) {
  const discovered = await discoverVercelProjects({
    token: env.VERCEL_API_TOKEN,
    teamId: env.VERCEL_TEAM_ID,
    fetchImpl,
  });

  const known = new Set(projects.map((p) => p.vercelProject).filter(Boolean));
  const ignored = new Set(excluded);
  const extra = discovered
    .filter((p) => !known.has(p.vercelProject) && !ignored.has(p.vercelProject))
    .sort((a, b) => b.updatedAt - a.updatedAt)
    .map((p) => ({
      id: p.vercelProject,
      vercelProject: p.vercelProject,
      url: p.url,
      category: 'Novo projeto',
      technologies: p.technologies ?? '',
      fallback: { name: prettifySlug(p.vercelProject), description: '' },
    }));

  // Projetos novos (descobertos) aparecem primeiro.
  const all = [...extra, ...projects];
  const metadata = await Promise.all(all.map((p) => fetchMetadata(p.url, fetchImpl)));
  return all.map((p, i) => mergeProject(p, metadata[i]));
}
